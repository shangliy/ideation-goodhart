"""Synthetic demo grid: a simulated recommender trained under 900 hyperparameter settings on three synthetic tasks, 3 seeds each.

The simulator plants five interactions, some that a practitioner would expect and some that run against common advice,
so the demo shows whether a generator finds effects its prior does not predict. Nothing here is real data.
"""
import csv, itertools, math
import numpy as np

GRID = dict(model=['mf', 'gru', 'transformer'], emb_dim=[16, 32, 64, 128, 256], lr=[0.0001, 0.0003, 0.001, 0.003, 0.01],
            dropout=[0.0, 0.1, 0.3, 0.5], batch=[256, 1024, 4096])
TASKS = dict(task_a=(20.0, 1.0), task_b=(12.0, 0.7), task_c=(30.0, 1.3))  # base recall and effect scale
DESCRIBE = ('Synthetic benchmark generated by `ideagen demo` (simulated data, not real results): a sequential recommender trained under '
            'every combination of the hyperparameters below on three synthetic tasks, 3 seeds each. The simulator follows familiar '
            'hyperparameter behaviour but also contains a few planted interaction effects.')


def score(model, emb_dim, lr, dropout, batch, scale, rng):
    le, ll = math.log2(emb_dim / 16), math.log10(lr)
    s = 1.2 * le - 2.0 * (ll + 3) ** 2 + {'mf': 0, 'gru': 1.5, 'transformer': 2.5}[model] - 0.5 * math.log2(batch / 256) / 2
    s += 2.0 * dropout * (model == 'transformer')                      # expected: transformers need dropout
    s += 1.0 * math.log2(batch / 256) * (lr >= 0.003)                  # expected: big batches want big learning rates
    s -= 3.0 * (emb_dim == 256) * (model == 'mf')                      # against advice: the widest MF embedding hurts
    s += 4.0 * (dropout == 0.5) * (emb_dim <= 32)                      # against advice: heavy dropout pays off only for small embeddings
    s -= 3.5 * (lr == 0.01) * (model == 'gru')                         # against advice: the GRU, not the transformer, breaks at lr 0.01
    return s * scale + rng.normal(0, 1.0)


def write(path, seeds=3, seed=0):
    rng = np.random.default_rng(seed)
    with open(path, 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['task', 'seed', *GRID, 'recall_at_20'])
        for task, (base, scale) in TASKS.items():
            for cfg in itertools.product(*GRID.values()):
                for s in range(seeds):
                    w.writerow([task, s, *cfg, round(base + score(*cfg, scale, rng), 3)])
    return path
